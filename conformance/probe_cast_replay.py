#!/usr/bin/env python3
"""Oracle half of the cast-replay differential harness.

Replays each case in ``corpus/cast_replay_cases.json`` through
:func:`termproof.cast_video.frames_from_cast` — a one-event cast of the case's
``columns`` x ``rows`` whose output is the case's ``output`` — and records the
final frame: each row's cells as ``text`` and ``width``, and the cursor.

It exists because no other harness reaches a terminal emulator's grid. The step
corpus drives a real child but compares a verdict and a detail string; the
evidence-manifest scenario has the port replay a cast and then throws the frames
away. So the two emulators behind cast playback — ``pyte`` here, ``avt`` in the
port — were compared by nothing, and a wide glyph overwritten on its second
column came back as three different screens from ``pyte``, ``avt`` 0.16 and
``avt`` 0.18 with every gate green (#209, found reviewing #220).

Only ``text``, ``width`` and the cursor are recorded. Colour and the SGR
attributes are a different question with known answers of their own — ``pyte``
has no dim — and recording them here would make every case about that.

The recorded environment is written into the header because the screen is
``pyte``'s and each cell's width is CPython's ``unicodedata``.

Regenerate deliberately::

    cd /path/to/termproof/python
    TERMPROOF_PYTHON_REPO=$PWD uv run python \\
        ../conformance/probe_cast_replay.py \\
        > ../conformance/corpus/cast_replay.expected.json
"""

from __future__ import annotations

import importlib.metadata
import json
import os
import platform
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, os.environ.get("TERMPROOF_PYTHON_REPO", str(Path(__file__).parent.parent / "python")))

from termproof.cast_video import frames_from_cast  # noqa: E402

CASES = Path(__file__).parent / "corpus" / "cast_replay_cases.json"


def run(case: dict[str, object], directory: Path) -> dict[str, object]:
    cast = directory / "case.cast"
    header = {"version": 2, "width": case["columns"], "height": case["rows"]}
    cast.write_text(
        json.dumps(header) + "\n" + json.dumps([0.0, "o", case["output"]]) + "\n",
        encoding="utf-8",
    )
    # The last frame is the final screen on both sides; how many frames lead up
    # to it is frame timing, which is not what this layer compares.
    final = frames_from_cast(cast)[-1]
    return {
        "name": case["name"],
        "rows": [[{"text": cell.text, "width": cell.width} for cell in row] for row in final.rows],
        "cursor": {
            "row": final.cursor_row,
            "column": final.cursor_column,
            "hidden": final.cursor_hidden,
        },
    }


def main() -> None:
    cases = json.loads(CASES.read_text(encoding="utf-8"))
    with tempfile.TemporaryDirectory() as tmpdir:
        recorded = [run(case, Path(tmpdir)) for case in cases]
    document = {
        "_comment": (
            "Generated by conformance/probe_cast_replay.py against the Python "
            "implementation. Do not hand-edit; regenerate instead."
        ),
        "environment": {
            "python": platform.python_version(),
            "pyte": importlib.metadata.version("pyte"),
        },
        "cases": recorded,
    }
    json.dump(document, sys.stdout, indent=2, ensure_ascii=False)
    sys.stdout.write("\n")


if __name__ == "__main__":
    main()
