#!/usr/bin/env python3
"""Oracle half of the selection differential harness.

Drives the real Python :func:`termproof.selection.select_names` over
``corpus/selection_cases.json`` and records, for each case, the ordered
list of names it selected into ``corpus/selection.expected.json``. The
Rust half replays the same cases through
``termproof::selection::select_names`` and compares the lists exactly.

A case is ``candidates`` (``name`` plus ``ci_paths`` globs), the
``changed_files`` a change touched, and the optional ``always``,
``harness_paths`` and ``root_marker`` — every input
:func:`select_names` takes. Most pattern cases carry one candidate with
one glob and one changed file, so "selected" reads directly as "this
glob matched this path" and a divergence names the pattern that
separates ``fnmatch`` from ``globset``. The list-level cases carry
several candidates, so candidate order, the always set, duplicates and
the harness fallback are compared as selections rather than assumed.

This half records the Python selections as they are. The known
divergences — patterns ``globset`` refuses to compile being literal
text here, brace alternates and ``[^...]`` negation and zero-directory
``**`` meaning things ``fnmatch`` does not mean, the root marker being
kept here and stripped there, and the harness rule taking globs here
against a single literal prefix there (#209) — are **not** recorded
here: they are named allowances with pinned Rust answers in the Rust
test, so the checked-in expectation stays the oracle's testimony and
each allowance has to be edited deliberately, in code, if either side
changes.

One reading note: Python selects case-sensitively here because
``fnmatch.fnmatch`` only folds case where ``os.path.normcase`` does —
in practice, Windows. The corpus is recorded on POSIX and measures
POSIX behaviour; the ``platform`` in the environment block is what
says so.

Regenerate deliberately::

    cd /path/to/termproof/python
    TERMPROOF_PYTHON_REPO=$PWD uv run python \\
        ../conformance/probe_selection.py \\
        > ../conformance/corpus/selection.expected.json
"""

from __future__ import annotations

import json
import os
import platform
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, os.environ.get("TERMPROOF_PYTHON_REPO", str(Path(__file__).parent.parent / "python")))

from termproof.selection import select_names  # noqa: E402

CASES = Path(__file__).parent / "corpus" / "selection_cases.json"


def run(case: dict[str, Any]) -> dict[str, Any]:
    candidates = [(entry["name"], entry["ci_paths"]) for entry in case["candidates"]]
    selected = select_names(
        candidates,
        case["changed_files"],
        always=case.get("always", ()),
        harness_paths=case.get("harness_paths", ()),
        root_marker=case.get("root_marker"),
    )
    # A list, in candidate order: the order is part of what is compared.
    return {"name": case["name"], "selected": selected}


def main() -> None:
    cases = json.loads(CASES.read_text(encoding="utf-8"))
    names = [case["name"] for case in cases]
    if len(set(names)) != len(names):
        raise SystemExit("selection_cases.json carries a duplicate case name")
    document = {
        "_comment": (
            "Generated by conformance/probe_selection.py against the Python "
            "implementation. Do not hand-edit; regenerate instead."
        ),
        "environment": {
            "python": platform.python_version(),
            "platform": platform.system(),
        },
        "cases": [run(case) for case in cases],
    }
    json.dump(document, sys.stdout, indent=2, ensure_ascii=False)
    sys.stdout.write("\n")


if __name__ == "__main__":
    main()
